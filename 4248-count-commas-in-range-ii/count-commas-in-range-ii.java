class Solution {
    public long countCommas(long n) {
        // long ans=0;
        // while(n!=0){
        //     n=n/1000;
        // }
        // return ans;

        if(n<1000){
            return 0;
        }
        if(n<1000000){
            return n-999;
        }
        if(n<1000000000){
            return (n-999999)*2+999999-999;
        }
        if(n<1000000000000L){
            return (n-999999999)*3+(999999999-999999)*2+999999-999;
        }
        if(n<1000000000000000L){
            return (n-999999999999L)*4+(999999999999L-999999999)*3+(999999999-999999)*2+999999-999;
        }
        if(n==1000000000000000L){
            return (999999999999999L-999999999999L)*4+(999999999999L-999999999)*3+(999999999-999999)*2+999999-999+5;
        }
        return 0;
    }
}